#include <iostream>
using namespace std;

int main() {
    // Define and initialize array
    int arr[5] = {5, 7, 11, 14, 20};

    // Using for loop to print array elements
    cout << "Array elements are:\n";

    for (int i = 0; i < 5; i++) {
        cout << arr[i] << endl;
    }

    return 0;
}